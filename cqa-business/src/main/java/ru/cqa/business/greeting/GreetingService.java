package ru.cqa.business.greeting;

/**
 * Порт: формирует приветствие адресату типа {@code T}.
 *
 * <p>Шаблон для роста приложения: новый вид адресата — это новый класс,
 * реализующий этот интерфейс. Ни реестр, ни существующие реализации,
 * ни веб-слой при этом не меняются.
 *
 * <p>Тип адресата объявляется явно через {@link #subjectType()}, а не
 * вычисляется рефлексией. Причина практическая: у лямбды параметр типа
 * стёрт, и {@code ResolvableType} на ней уже ничего не определит.
 *
 * @param <T> тип адресата приветствия
 */
public interface GreetingService<T> {

    /**
     * @return класс адресата, который обслуживает эта реализация
     */
    Class<T> subjectType();

    /**
     * @param subject адресат приветствия
     * @return текст приветствия
     */
    String greet(T subject);
}
