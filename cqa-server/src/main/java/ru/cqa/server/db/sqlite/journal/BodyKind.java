package ru.cqa.server.db.sqlite.journal;

/** Тип тела запроса или ответа в журнале; в БД хранится имя константы. */
public enum BodyKind {

    /** Тела нет или оно нулевой длины. */
    EMPTY,

    /** Валидный JSON. */
    JSON,

    /** Похоже на XML (в том числе SOAP): начинается с {@code <}. Корректность не проверяется. */
    XML,

    /** Прочий текст, в том числе невалидный JSON. */
    TEXT,

    /** Не текст в заявленной кодировке — хранится в Base64. */
    BINARY
}
